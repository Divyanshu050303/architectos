"""An evolution candidate: a proposed set of configuration changes to one exact baseline revision,
generated by one versioned rule from current evidence — a proposal, never applied by the engine.

- The **baseline** is the architecture, revision number and content hash the candidate is against.
- The **changes** are configuration changes of existing nodes and connections (the simulation's
  ``ConfigurationChange``, validated by the Architecture IR's property specifications). They are
  applied only to an in-memory overlay; the canonical architecture is never modified.
- **Evidence** references say which stored analysis (revision, content hash, model version), which
  finding or scaling option, requirement or goal the candidate rests on. Only ``current`` evidence
  (of the baseline's exact content) can support a candidate.
- **Effects** (benefits, trade-offs, operational complexity, migration considerations, risks) each
  state their dimension and their basis: ``modeled`` by an engine, stated by the ``rule``, or a
  ``consideration`` for human review. Nothing is scored, weighted or ranked.
- The **id** is derived from the rule, the baseline and the changes: the same proposal always has
  the same id.
"""

